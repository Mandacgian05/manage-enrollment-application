-- Online requirement uploads (completes the US-10 attachment criterion).
--
-- Applicants may upload one PDF, JPG or PNG (up to 10 MB) per requirement after their
-- application is saved. Files go straight to a PRIVATE storage bucket through one-time
-- upload links that only the enrollment server can create; the server then checks each
-- file before recording it here. Only an active Registrar can read the files, through
-- short-lived signed links, and every opening is written to the audit log.
--
-- Undo: supabase/rollback/202611190001_application_document_uploads_rollback.sql
begin;

-- Private Document Bucket START
-- Not public: there is no public URL for any file. The bucket itself rejects other file
-- types and anything over 10 MB, in addition to the server's own checks.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('application-documents', 'application-documents', false, 10485760,
        array['application/pdf', 'image/jpeg', 'image/png'])
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;
-- Private Document Bucket END

-- Document Records START
-- One file per requirement per application; uploading again replaces it.
alter table public.application_documents
    add column if not exists content_type text,
    add column if not exists file_size_bytes integer;

alter table public.application_documents
    add constraint application_documents_document_type_format
        check (document_type ~ '^[a-z0-9-]{1,60}$'),
    add constraint application_documents_content_type_allowed
        check (content_type is null or content_type in ('application/pdf', 'image/jpeg', 'image/png')),
    add constraint application_documents_file_size_range
        check (file_size_bytes is null or file_size_bytes between 1 and 10485760),
    -- Paths are generated by the server: <application id>/<requirement>/<random id>.<ext>
    add constraint application_documents_storage_path_format
        check (storage_path ~ '^[0-9]{1,19}/[a-z0-9-]{1,60}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(pdf|jpg|png)$');

create unique index if not exists application_documents_one_per_requirement
    on public.application_documents (application_id, document_type);
-- Document Records END

-- Registrar File Access START
-- Signed download links are created with the Registrar's own session, so storage checks
-- this policy. No insert, update or delete policy exists: browsers can never change files.
drop policy if exists "Registrar reads application documents" on storage.objects;
create policy "Registrar reads application documents"
    on storage.objects for select to authenticated
    using (bucket_id = 'application-documents' and public.get_staff_portal_role() = 'registrar');
-- Registrar File Access END

-- Review Application Details & Documents START
-- Same as 202611160001, now also returning each document's type, size and file type.
create or replace function public.get_registrar_application(p_reference text)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
    result jsonb;
begin
    perform public.require_registrar();
    select (to_jsonb(a) - 'submitter_ip_hash' - 'period_id') || jsonb_build_object(
        'school_year', p.school_year,
        'guardians', coalesce((select jsonb_agg(jsonb_build_object(
                'relationship', g.relationship, 'full_name', g.full_name,
                'occupation', g.occupation, 'contact_number', g.contact_number) order by g.relationship)
            from public.application_guardians g where g.application_id = a.id), '[]'::jsonb),
        'documents', coalesce((select jsonb_agg(jsonb_build_object(
                'id', d.id, 'document_type', d.document_type, 'uploaded_at', d.uploaded_at,
                'content_type', d.content_type, 'file_size_bytes', d.file_size_bytes) order by d.uploaded_at)
            from public.application_documents d where d.application_id = a.id), '[]'::jsonb),
        'requirement_checks', coalesce((select jsonb_object_agg(c.requirement_key, c.received)
            from public.application_requirement_checks c where c.application_id = a.id), '{}'::jsonb))
    into result
    from public.enrollment_applications a
    join public.enrollment_periods p on p.id = a.period_id
    where a.reference_no = p_reference;
    return result;
end;
$$;
-- Review Application Details & Documents END

-- Open Uploaded Document START
-- Checks the Registrar, writes the audit entry, and returns the storage path the portal
-- then signs for 60 seconds. The path never comes from the browser.
create function public.record_document_access(p_reference text, p_document_id bigint)
returns text
language plpgsql security definer set search_path = ''
as $$
declare
    actor_id bigint := public.require_registrar();
    app_id bigint;
    doc public.application_documents%rowtype;
begin
    select a.id into app_id from public.enrollment_applications a where a.reference_no = p_reference;
    select * into doc from public.application_documents d
    where d.id = p_document_id and d.application_id = app_id;
    if app_id is null or doc.id is null then
        raise no_data_found using message = 'Document not found';
    end if;

    insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_value, new_value)
    values (actor_id, 'application.document_view', 'enrollment_applications', app_id, null,
            jsonb_build_object('document_id', doc.id, 'document_type', doc.document_type));
    return doc.storage_path;
end;
$$;

revoke all on function public.record_document_access(text, bigint) from public, anon, authenticated;
grant execute on function public.record_document_access(text, bigint) to authenticated;
-- Open Uploaded Document END

commit;
